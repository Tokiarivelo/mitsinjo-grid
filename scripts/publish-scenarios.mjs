const countScenarios = (md) => md.split('\n').filter((l) => /^- \[[ xX]\] \*\*/.test(l)).length;
const img = ([name, alt], width) => `<img src="shots/${name}.jpg" alt="${alt}" width="${width}">`;
const GENERATED =
  '<!-- Generated by `make scenarios-publish` from the local test-scenarios/ folder. Edit the source, then re-run. -->';

if (!existsSync(SRC)) {
  console.error('test-scenarios/ is missing (local folder, see .claude/rules/test-scenarios.md)');
  process.exit(1);
}
mkdirSync(OUT, { recursive: true });

const rows = [];
let total = 0;
for (const page of PAGES) {
  const src = readFileSync(path.join(SRC, page.file), 'utf8');
  const n = countScenarios(src);
  total += n;
  const width = page.shots.length > 1 ? `${Math.floor(98 / page.shots.length)}%` : '100%';
  const gallery = `<p>\n${page.shots.map((s) => img(s, width)).join('\n')}\n</p>`;
  const head = `${GENERATED}\n\n[← All scenarios](README.md) · ${page.where} · **${n} scenarios** · written in French (UI labels from \`fr.json\`)\n\n${gallery}\n\n`;
  writeFileSync(path.join(OUT, page.file), head + src);
  rows.push(
    `| [${page.title}](${page.file}) | ${page.where} | ${img(page.shots[0], 240)} | ${n} |`
  );
}

const local = readFileSync(path.join(SRC, 'README.md'), 'utf8');
const rule = (local.split("## Règle d'or")[1] || '').split('\n## ')[0].trim();
const index = `${GENERATED}

# Manual test scenarios

![${total} manual test scenarios across ${PAGES.length} pages](../images/test-scenarios-banner.jpg)

**${total} step-by-step checks** to try every screen yourself, each one written as
\`action → expected result\`. They are the checklists used while building Mitsinjo Grid; every visible change
added or updated its scenario. Scenarios are in French and use the French UI labels
(switch the app to **FR** in the header). All data is **simulated**.

## Run the app

\`\`\`bash
make dev-mock   # app + offline copilot (deterministic answers), no key needed
make dev        # same with the live Meta models (key in .env)
\`\`\`

## Pages

| Page | Where | Preview | Scenarios |
| ---- | ----- | ------- | --------- |
${rows.join('\n')}

## Golden rule (règle d'or)

${rule}
`;
writeFileSync(path.join(OUT, 'README.md'), index);

